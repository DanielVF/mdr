pub fn width(cp: u21) u2 {
    if (cp < 0x80) return 1;
    var lo: usize = 0;
    var hi: usize = ranges.len;
    while (lo < hi) {
        const mid = lo + (hi - lo) / 2;
        const r = ranges[mid];
        if (cp < r.first) hi = mid else if (cp > r.last) lo = mid + 1 else return r.cells;
    }
    return 1;
}

// Keep the current emoji pending across writes. Inline markup can split a
// single displayed sequence into several calls to the measuring writer.
pub const Measure = struct {
    completed: usize = 0,
    pending: u2 = 0,
    state: enum { text, pictograph, keycap, joiner } = .text,

    pub fn add(self: *Measure, cp: u21) void {
        switch (cp) {
            0xfe0e, 0xfe0f => {
                if (self.state == .pictograph or self.state == .keycap)
                    self.pending = if (cp == 0xfe0f) 2 else 1;
                return;
            },
            0x200d => {
                self.state = if (self.state == .pictograph) .joiner else .text;
                return;
            },
            0x1f3fb...0x1f3ff => if (self.state == .pictograph) {
                self.pending = 2;
                return;
            },
            0x20e3 => if (self.state == .keycap) {
                self.pending = 2;
                self.state = .text;
                return;
            },
            0xe0020...0xe007f => return, // Invisible tags in flag sequences.
            else => {},
        }
        const next: @TypeOf(self.state) = switch (cp) {
            '#', '*', '0'...'9' => .keycap,
            0x1f1e6...0x1f1ff, 0x1f3fb...0x1f3ff => .text,
            else => if (cp >= 128 and @import("unicode_properties.zig").isEmoji(cp)) .pictograph else .text,
        };
        if (self.state == .joiner and next == .pictograph) {
            self.pending = 2;
        } else {
            self.completed += self.pending;
            self.pending = width(cp);
        }
        self.state = next;
    }

    pub fn cells(self: Measure) usize {
        return self.completed + self.pending;
    }
};
